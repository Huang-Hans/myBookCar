import { ref } from 'vue'

export type LocaleCode = 'EN' | 'ZH_HANT' | 'ZH_HANS'

const storageKey = 'lmsDriverLocale'

export function normalizeLocale(value: unknown): LocaleCode {
  if (value === '繁體中文') return 'ZH_HANT'
  if (value === '简体中文') return 'ZH_HANS'
  return value === 'ZH_HANT' || value === 'ZH_HANS' ? value : 'EN'
}

function storedLocale(): LocaleCode {
  try { return normalizeLocale(uni.getStorageSync(storageKey) || uni.getStorageSync('lmsDriverLanguage')) }
  catch { return 'EN' }
}

export const locale = ref<LocaleCode>(storedLocale())

export function setLocale(value: LocaleCode): void {
  locale.value = value
  try { uni.setStorageSync(storageKey, value) } catch { /* The current session still uses the selected language. */ }
}

