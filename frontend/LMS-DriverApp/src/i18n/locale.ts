export function t(source: string): string {
  const translation = messages[source] ?? messages[source.charAt(0).toUpperCase() + source.slice(1)]
  return locale.value === 'ZH_HANT' ? translation?.[0] ?? source : locale.value === 'ZH_HANS' ? translation?.[1] ?? source : source
}

export function localeTag(): string {
  return locale.value === 'ZH_HANT' ? 'zh-HK' : locale.value === 'ZH_HANS' ? 'zh-CN' : 'en-GB'
}
