export function useLocale() {
  function t(key: string): string {
    if (activeLocale.value === 'en') return key
    const bookingCreated = /^Booking (.+) was created in this local demo\.$/.exec(key)
    if (bookingCreated) return activeLocale.value === 'zh-Hans'
      ? `预约 ${bookingCreated[1]} 已在本地演示中创建。`
      : `預約 ${bookingCreated[1]} 已在本機示範中建立。`
    const translations = activeLocale.value === 'zh-Hans' ? zhHans : zhHant
    return translations.get(key) ?? key
  }
  function setLocale(value: Locale): void { activeLocale.value = value }
  const dateLocale = computed(() => ({ en: 'en-GB', 'zh-Hant': 'zh-Hant-MO', 'zh-Hans': 'zh-Hans-CN' })[activeLocale.value])
  const confirmationLanguage = computed(() => ({ en: 'EN', 'zh-Hant': 'ZH_HANT', 'zh-Hans': 'ZH_HANS' } as const)[activeLocale.value])
  return { locale: readonly(activeLocale), dateLocale, confirmationLanguage, setLocale, t }
}

watch(activeLocale, (value) => {
  if (typeof document !== 'undefined') {
    document.documentElement.lang = value
  }
  if (typeof window !== 'undefined') {
    try { window.localStorage.setItem(storageKey, value) } catch { /* Storage may be unavailable. */ }
  }
}, { immediate: true })
